import {writeFileSync} from 'node:fs';
const start=Date.parse('2026-09-05T00:00:00Z');
const configs={
 overnight:{rps:12,inputTokens:1200,outputTokens:300,sharedPrefix:.65,burstiness:.1,mix:{gemma:.45,qwen:.3,kimi:.25}},
 prefix:{rps:24,inputTokens:3500,outputTokens:300,sharedPrefix:.9,burstiness:.15,mix:{gemma:.45,qwen:.3,kimi:.25}},
 surge:{rps:27,inputTokens:1200,outputTokens:300,sharedPrefix:.65,burstiness:.15,mix:{gemma:.25,qwen:.5,kimi:.25}},
 mixed:{rps:18,inputTokens:1600,outputTokens:400,sharedPrefix:.5,burstiness:.2,mix:{gemma:.4,qwen:.3,kimi:.3}}
};
const windows=Array.from({length:576},(_,i)=>{
 const hour=Math.floor(i/12)%24,phase=hour<7||hour>=22?'overnight':hour>=8&&hour<12?'prefix':hour>=15&&hour<18?'surge':'mixed';
 const c=configs[phase],factor=1+.04*Math.sin(i*1.73)+(i>=288?.03:0);
 return {startTime:new Date(start+i*300000).toISOString(),durationSeconds:300,phase,offeredRps:+(c.rps*factor).toFixed(3),inputTokens:c.inputTokens,outputTokens:c.outputTokens,sharedPrefix:c.sharedPrefix,burstiness:c.burstiness,concurrency:128,ttftTargetMs:800,tokenTargetMs:70,mix:c.mix};
});
const data={schemaVersion:1,kind:'inference-autopilot.traffic-history',source:'synthetic',rateKind:'offered',id:'synthetic-fleet-48h-v1',startTime:new Date(start).toISOString(),endTime:new Date(start+48*3600000).toISOString(),intervalSeconds:300,windows};
const json=JSON.stringify(data,null,2)+'\n';
writeFileSync('public/data/synthetic-fleet-48h.json',json);
writeFileSync('lib/sample-traffic-data.ts','// Generated by scripts/generate-sample-traffic.mjs; synthetic, no customer data.\nconst data = '+JSON.stringify(data)+';\nexport default data;\n');
console.log('Generated 48 hours / 576 five-minute aggregate windows.');
